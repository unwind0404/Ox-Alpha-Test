// reply-templates: детерминированные шаблоны по рейтингу.
// Используется стратегией 'templates' и fallback для 'llm'/'drafts'.

import type { Rating } from './types.js'

const TEMPLATES: Record<number, string> = {
  5: 'Здравствуйте! Огромное спасибо за ваш отзыв и высокую оценку! Нам очень приятно, что покупка вас порадовала. Будем рады видеть вас снова!',
  4: 'Здравствуйте! Благодарим за отзыв и хорошую оценку! Рады, что покупка вам понравилась. Будем стараться стать ещё лучше. Ждём вас снова!',
  3: 'Здравствуйте! Спасибо за ваш отзыв. Нам жаль, что опыт покупки не был идеальным. Напишите, пожалуйста, что можно улучшить — мы обязательно прислушаемся.',
  2: 'Здравствуйте! Приносим извинения за доставленные неудобства. Ваш отзыв важен для нас. Пожалуйста, напишите, что пошло не так, и мы постараемся решить проблему.',
  1: 'Здравствуйте! Искренне сожалеем, что покупка вас разочаровала. Мы обязательно разберёмся в ситуации. Свяжитесь с нами, пожалуйста, и мы сделаем всё возможное, чтобы исправить положение.',
}

/** Получить шаблон по рейтингу. */
export function templateForRating(rating: Rating | null): string {
  if (rating !== null && TEMPLATES[rating]) {
    return TEMPLATES[rating]!
  }
  return 'Здравствуйте! Спасибо за ваш отзыв. Если у вас есть вопросы или пожелания — напишите нам, и мы обязательно поможем.'
}
